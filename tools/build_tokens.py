#!/usr/bin/env python3
"""Build CSS from a layered design-token file (primitive -> semantic -> component).

Reads a JSON token file (default: plugins/ultimatum/data/design-own/tokens/starter.tokens.json)
and writes two stylesheets beside it:

  <name>.css        plain CSS custom properties: primitives and component tokens on :root,
                    semantic roles on :root (light) and .dark (dark)
  <name>.theme.css  the same tokens for Tailwind CSS v4: primitives in @theme (so they make
                    utilities), semantic roles on :root/.dark, exposed through @theme inline

Every pair listed under "pairs" is checked in light and dark against its contrast floor
(WCAG 2.2: 4.5:1 for text, SC 1.4.3; 3:1 for control borders and focus rings, SC 1.4.11).
A failing pair stops the build.

    python3 tools/build_tokens.py                       # write the starter CSS
    python3 tools/build_tokens.py --check               # exit 1 if out of date or a pair fails
    python3 tools/build_tokens.py --in my.tokens.json --out-dir src/styles

Reference syntax: "{color.moss.600}" points at a primitive; "{primary}" at a semantic role.
Standard library only; no network.
"""
from __future__ import annotations

import json
import re
import sys
from argparse import ArgumentParser
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_palettes import contrast  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_IN = ROOT / "plugins" / "ultimatum" / "data" / "design-own" / "tokens" / "starter.tokens.json"
REF = re.compile(r"^\{([a-z0-9.-]+)\}$")
SIX_DIGIT_HEX = re.compile(r"#[\da-f]{6}", re.IGNORECASE)
HEAD = "/* Generated by tools/build_tokens.py from {src}. Edit the JSON, not this file. */\n"


def flatten(tree: dict, prefix: tuple[str, ...] = ()) -> dict[tuple[str, ...], str]:
    out: dict[tuple[str, ...], str] = {}
    for key, val in tree.items():
        if key.startswith("$"):
            continue
        path = prefix + (str(key),)
        if isinstance(val, dict):
            out.update(flatten(val, path))
        else:
            out[path] = str(val)
    return out


def prim_var(path: tuple[str, ...]) -> str:
    return "--" + "-".join(path)


class Tokens:
    def __init__(self, data: dict):
        self.prim = flatten(data.get("primitive", {}))
        self.sem: dict[str, dict[str, str]] = data.get("semantic", {})
        self.pairs: list[list] = data.get("pairs", [])
        self.comp = flatten(data.get("component", {}))
        self.errors: list[str] = []

    def ref_var(self, value: str, where: str) -> str:
        """Turn a value into CSS: a {ref} becomes var(--x); anything else passes through."""
        m = REF.match(value)
        if not m:
            return value
        name = m.group(1)
        if "." in name:
            path = tuple(name.split("."))
            if path not in self.prim:
                self.errors.append(f"{where}: unknown primitive {value}")
            return f"var({prim_var(path)})"
        if name not in self.sem:
            self.errors.append(f"{where}: unknown semantic role {value}")
        return f"var(--{name})"

    def resolve_hex(self, role: str, mode: str) -> str | None:
        entry = self.sem.get(role)
        if not entry:
            self.errors.append(f"pair: unknown role {role}")
            return None
        value = entry.get(mode, "")
        for _ in range(8):
            m = REF.match(value)
            if not m:
                break
            name = m.group(1)
            value = self.prim.get(tuple(name.split(".")), "") if "." in name else self.sem.get(name, {}).get(mode, "")
        if not SIX_DIGIT_HEX.fullmatch(value):
            self.errors.append(f"pair: {role} ({mode}) does not resolve to a #rrggbb colour")
            return None
        return value.lower()

    def check_pairs(self) -> list[tuple[str, str, str, float, float]]:
        rows = []
        for fg, bg, floor in self.pairs:
            for mode in ("light", "dark"):
                a, b = self.resolve_hex(fg, mode), self.resolve_hex(bg, mode)
                if a and b:
                    rows.append((mode, fg, bg, round(contrast(a, b), 2), float(floor)))
        return rows


def block(selector: str, lines: list[str]) -> str:
    return selector + " {\n" + "".join(f"  {ln}\n" for ln in lines) + "}\n"


def semantic_lines(t: Tokens, mode: str) -> list[str]:
    return [f"--{role}: {t.ref_var(v[mode], 'semantic.' + role)};" for role, v in t.sem.items()]


def component_lines(t: Tokens) -> list[str]:
    return [f"{prim_var(p)}: {t.ref_var(v, 'component.' + '.'.join(p))};" for p, v in t.comp.items()]


def render_plain(t: Tokens, src: str) -> str:
    prim = [f"{prim_var(p)}: {v};" for p, v in t.prim.items()]
    return (HEAD.format(src=src)
            + "\n/* 1. Primitives: raw values, never used directly by components */\n" + block(":root", prim)
            + "\n/* 2. Semantic roles, light (default) */\n" + block(":root", semantic_lines(t, "light"))
            + "\n/* 2. Semantic roles, dark: only the roles change */\n" + block(".dark", semantic_lines(t, "dark"))
            + "\n/* 3. Component tokens: point at roles, so they follow the mode */\n" + block(":root", component_lines(t)))


def render_tailwind(t: Tokens, src: str) -> str:
    theme = ["--color-*: initial;"]
    theme += [f"{prim_var(p)}: {v};" for p, v in t.prim.items()]
    inline = [f"--color-{role}: var(--{role});" for role in t.sem]
    inline += ["--radius-sm: calc(var(--radius) - 4px);", "--radius-md: calc(var(--radius) - 2px);",
               "--radius-lg: var(--radius);", "--radius-xl: calc(var(--radius) + 4px);"]
    return (HEAD.format(src=src)
            + '@import "tailwindcss";\n\n'
            + "/* Dark mode follows a .dark class on <html>, not only the OS setting */\n"
            + "@custom-variant dark (&:where(.dark, .dark *));\n\n"
            + "/* 1. Primitives: become utilities such as bg-moss-600, text-ink-900, p-4, rounded-lg */\n"
            + block("@theme", theme)
            + "\n/* 2. Semantic roles: plain variables, switched by .dark */\n"
            + block(":root", semantic_lines(t, "light")) + "\n" + block(".dark", semantic_lines(t, "dark"))
            + "\n/* 2b. Expose roles as utilities (bg-primary, text-muted-foreground); inline keeps var() live */\n"
            + block("@theme inline", inline)
            + "\n/* 3. Component tokens */\n" + block(":root", component_lines(t)))


def build(src: Path) -> tuple[dict[str, str], Tokens, list]:
    t = Tokens(json.loads(src.read_text(encoding="utf-8")))
    try:
        rel = src.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        rel = src.name
    stem = src.name.removesuffix(".json").removesuffix(".tokens")
    outs = {f"{stem}.tokens.css": render_plain(t, rel), f"{stem}.theme.css": render_tailwind(t, rel)}
    return outs, t, t.check_pairs()


def main(argv: list[str] | None = None) -> int:
    ap = ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--in", dest="src", type=Path, default=DEFAULT_IN, help="token JSON file")
    ap.add_argument("--out-dir", type=Path, help="where to write the CSS (default: beside the JSON)")
    ap.add_argument("--check", action="store_true", help="exit 1 if outputs are stale or a pair fails")
    args = ap.parse_args(argv)
    outs, t, rows = build(args.src)
    out_dir = args.out_dir or args.src.parent
    failed = [r for r in rows if r[3] < r[4]]
    for mode, fg, bg, ratio, floor in rows:
        mark = "ok  " if ratio >= floor else "FAIL"
        print(f"{mark} {mode:5} {fg} on {bg}: {ratio}:1 (floor {floor}:1)")
    for err in t.errors:
        print("error:", err)
    if failed or t.errors:
        print(f"{len(failed)} pair(s) below floor, {len(t.errors)} error(s)")
        return 1
    stale = [n for n, text in outs.items()
             if not ((out_dir / n).is_file() and (out_dir / n).read_text(encoding="utf-8") == text)]
    if args.check:
        print("tokens: out of date: " + ", ".join(stale) if stale else "tokens: up to date")
        return 1 if stale else 0
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in outs.items():
        (out_dir / name).write_text(text, encoding="utf-8")
        print("wrote", (out_dir / name))
    return 0


if __name__ == "__main__":
    sys.exit(main())
